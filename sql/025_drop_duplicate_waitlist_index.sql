-- idx_waitlist_email, a plain index on the same column. The signup's upsert (`onConflict: 'email'`,
-- api/waitlist.ts) needs the unique one, and any other lookup by email can use it too, so the
-- second index only costs space and a little work on every write. The constraint and its index stay.
--
-- Check before applying (expect waitlist_pkey, waitlist_email_key and idx_waitlist_email):
--   select indexname, indexdef from pg_indexes where schemaname = 'public' and tablename = 'waitlist';
-- and after (expect waitlist_pkey and waitlist_email_key).
--
-- UNDO: create index if not exists idx_waitlist_email on public.waitlist (email);

drop index if exists public.idx_waitlist_email;
